"""Assemble single-file code.py bundles for the Lemma functions.

Lemma function bundles only ship code.py — sibling modules are NOT importable
(proven: `ModuleNotFoundError` on import). So we inline the lemma-map core
modules into one file per function. lemma-map/ stays the single source of truth;
re-run this whenever those modules change:

    python backend/forge-fn/build.py
"""
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent
CORE = ROOT.parent / "lemma-map"


def strip_module(name: str) -> str:
    """Return a module's body with top-level imports (incl. multi-line) and the
    CLI main()/__main__ tail removed, so it can be concatenated into one file."""
    src = (CORE / f"{name}.py").read_text()
    lines = src.splitlines()
    out: list[str] = []
    i, n = 0, len(lines)
    while i < n:
        line = lines[i]
        if re.match(r"^def main\(", line) or re.match(r"^if __name__", line):
            break  # drop the CLI entrypoint entirely
        if re.match(r"^(import |from )", line):
            if "(" in line and ")" not in line:  # multi-line parenthesized import
                while i < n and ")" not in lines[i]:
                    i += 1
                i += 1
                continue
            i += 1
            continue
        out.append(line)
        i += 1
    return "\n".join(out).strip()


