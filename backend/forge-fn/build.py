def assemble(fn: str, inp: str, out: str, modules: list[str], extra: str) -> str:
    parts = [HEADER.format(fn=fn, inp=inp, out=out)]
    for m in modules:
        parts.append(BANNER.format(name=m))
        parts.append(strip_module(m))
    parts.append(extra)
    return "\n".join(parts).rstrip() + "\n"


def main() -> None:
    api = assemble(
        "forge_api", "ForgeApiInput", "ForgeApiResult",
        ["_forge", "generate_architecture", "guide_node", "approvals",
         "export_repo", "digest"],
        API_EXTRA)
    gen = assemble(
        "forge_generate", "ForgeGenerateInput", "ForgeGenerateResult",
        ["_forge", "generate_architecture"],
        GEN_EXTRA)

    (ROOT / "functions" / "forge_api").mkdir(parents=True, exist_ok=True)
    (ROOT / "functions" / "forge_generate").mkdir(parents=True, exist_ok=True)
    (ROOT / "functions" / "forge_api" / "code.py").write_text(api)
    (ROOT / "functions" / "forge_generate" / "code.py").write_text(gen)
    print(f"wrote forge_api/code.py ({len(api.splitlines())} lines)")
    print(f"wrote forge_generate/code.py ({len(gen.splitlines())} lines)")


if __name__ == "__main__":
    main()
