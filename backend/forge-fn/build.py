# ======================================================================
# Forge API dispatcher (ported from backend/main.py routes)
# ======================================================================
_ARCH_LAYERS = ("client", "api", "data", "integration", "infra")


def _node_slug(text):
    s = re.sub(r"[^a-z0-9]+", "-", (text or "").strip().lower()).strip("-")
    return s or "node"


def _unique_node_slug(text, existing):
    base = _node_slug(text)
    slug, i = base, 2
    while slug in existing:
        slug, i = f"{base}-{i}", i + 1
    return slug


def _rf_nodes(nodes):
    return [{
        "id": n.get("slug"),
        "type": "forge",
        "position": {"x": n.get("pos_x") or 0.0, "y": n.get("pos_y") or 0.0},
        "data": {
            "slug": n.get("slug"), "title": n.get("title"), "summary": n.get("summary"),
            "layer": n.get("layer"), "kind": n.get("kind"), "status": n.get("status"),
        },
    } for n in nodes]


def _rf_edges(edges):
    out = []
    for e in edges:
        s, t = e.get("source"), e.get("target")
        out.append({"id": e.get("id") or f"{s}->{t}", "source": s, "target": t})
    return out


def _load_project(pod, project_id):
    proj = retry(lambda: pod.records.get("projects", project_id))
    if not proj:
        raise ValueError(f"project {project_id} not found")
    nodes = list_all(pod, "nodes", project_id=project_id)
    edges = list_all(pod, "edges", project_id=project_id)
    tasks = sorted(list_all(pod, "tasks", project_id=project_id),
                   key=lambda t: t.get("priority", 0))
    return {
        "project": {"id": proj.get("id"), "name": proj.get("name"),
                    "status": proj.get("status"),
                    "design_locked": proj.get("design_locked"),
                    "summary": proj.get("summary"), "prompt": proj.get("prompt")},
        "graph": {"nodes": _rf_nodes(nodes), "edges": _rf_edges(edges)},
        "tasks": tasks,
    }


