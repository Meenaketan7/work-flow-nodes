def _dispatch(pod, d: "ForgeApiInput"):
    a = d.action
    if a == "projects":
        items = retry(lambda: pod.records.list(
            "projects", limit=100,
            sort=[{"field": "created_at", "direction": "desc"}])).to_dict()["items"]
        return {"projects": [{
            "id": p.get("id"), "name": p.get("name"), "status": p.get("status"),
            "design_locked": p.get("design_locked"), "created_at": p.get("created_at"),
        } for p in items]}
    if a == "project":
        return _load_project(pod, d.project_id)
    if a == "guidance":
        return guide_node(pod, d.project_id, d.node_id, d.question, refresh=d.refresh)
    if a == "node_status":
        return set_node_status(pod, d.project_id, d.node_id or d.slug, d.status)
    if a == "lock":
        return lock_design(pod, d.project_id)
    if a == "unlock":
        return unlock_design(pod, d.project_id)
    if a == "export":
        return export_repo(pod, d.project_id, owner=d.owner, repo=d.repo, push=d.push)
